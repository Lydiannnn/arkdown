import { fireEvent } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import {
  createLocalMediaElement,
  imageAlignmentIconCssSize,
  isLocalMediaClosingHtml,
  localMediaClosingMatchesOpening,
  parseLocalMediaHtml,
  parseLocalMarkdownImage,
  serializeLocalImage,
  updateLocalImageDescriptor,
} from '../../src/renderer/editor/local-media-view'
import { externalAssetUrl } from '../../src/shared/local-resource-path'

const audioSource = 'C:\\Workspace\\assets\\sample.mp3'
const videoSource = 'C:\\Workspace\\assets\\sample.mp4'
const audioOpening = `<audio controls preload="metadata" src="${audioSource}">`
const videoOpening = `<video class="arkdown-video" controls preload="metadata" src="${videoSource}">`
const audioHtml = audioOpening + '</audio>'
const videoHtml = videoOpening + '</video>'

describe('local media HTML parser', () => {
  it('roundtrips relative image alignment and zoom through HTML with the document base', () => {
    const initial = parseLocalMarkdownImage({ src: '../images/photo.png', alt: 'Photo' }, 'C:\\Notes\\docs\\note.md')!
    const updated = updateLocalImageDescriptor(initial, { alignment: 'right', zoom: 75 })!
    const html = serializeLocalImage(updated)
    expect(parseLocalMediaHtml(html, 'C:\\Notes\\docs\\note.md')).toMatchObject({
      source: '../images/photo.png', previewSource: 'C:\\Notes\\images\\photo.png', alignment: 'right', zoom: 75,
    })
    expect(parseLocalMediaHtml(html, 'D:\\Copies\\docs\\saved.md')?.previewSource).toBe('D:\\Copies\\images\\photo.png')
  })

  it.each([
    ['file:///C:/Notes/my%20%E5%9B%BE.png', 'C:\\Notes\\my 图.png'],
    ['assets/my%20%E5%9B%BE.png', 'C:\\Notes\\assets\\my 图.png'],
    ['C:\\Notes\\literal%20.png', 'C:\\Notes\\literal%20.png'],
  ])('previews %s without rewriting the serialized source', (source, resolved) => {
    const markdown = parseLocalMarkdownImage({ src: source }, 'C:\\Notes\\note.md')!
    expect(markdown?.previewSource ?? markdown?.source).toBe(resolved)
    const html = parseLocalMediaHtml(serializeLocalImage(markdown), 'C:\\Notes\\note.md')!
    expect(html?.previewSource ?? html?.source).toBe(resolved)
    expect(html?.source).toBe(source)
  })

  it('accepts safely reordered wrapped HTML with dimensions and entities', () => {
    const parsed = parseLocalMediaHtml('<img\n height="120" alt="A &#x56FE; &amp; B"\n width="240" src="assets/a&#32;b.png" style="margin-right: 0; display: block; margin-left: auto" >', 'C:\\Notes\\note.md')
    expect(parsed).toMatchObject({ source: 'assets/a b.png', previewSource: 'C:\\Notes\\assets\\a b.png', alt: 'A 图 & B', width: 240, height: 120, alignment: 'right' })
    expect(parseLocalMediaHtml(serializeLocalImage(updateLocalImageDescriptor(parsed!, { zoom: 80 })!), 'C:\\Notes\\note.md')).toMatchObject({ width: 240, height: 120, zoom: 80 })
  })

  it('decodes HTML entities once and accepts a quoted greater-than sign', () => {
    const parsed = parseLocalMediaHtml('<img src="C:\\Notes\\a.png" alt="A > B &#38;quot; &#x56FE;">')
    expect(parsed?.alt).toBe('A > B &quot; 图')
  })

  it.each(['onerror="alert(1)"', 'style="position:fixed;left:0"', 'style="background:url(javascript:alert(1))"'])('rejects unsafe attributes on an otherwise supported absolute image: %s', (attributes) => {
    expect(parseLocalMediaHtml(`<img src="C:\\Notes\\a.png" ${attributes}>`)).toBeNull()
  })

  it.each([
    '<img src="assets/a.png" onerror="alert(1)">',
    '<img src="assets/a.png" style="background:url(javascript:alert(1))">',
    '<img src="assets/a.png" width="-1">',
    '<img src="assets/a.png" src="assets/b.png">',
    '<img src="javascript:alert(1)">',
    '<img src="file:///C:/a.png?query=1">',
  ])('keeps unsafe image HTML as text: %s', (html) => {
    expect(parseLocalMediaHtml(html, 'C:\\Notes\\note.md')).toBeNull()
  })
  it('accepts only canonical audio and video generated by Arkdown', () => {
    expect(parseLocalMediaHtml(audioHtml)).toEqual({ kind: 'audio', source: audioSource, alt: '', zoom: null })
    expect(parseLocalMediaHtml(videoHtml)).toEqual({ kind: 'video', source: videoSource, alt: '', zoom: null })
    expect(parseLocalMediaHtml(audioOpening)).toEqual({ kind: 'audio', source: audioSource, alt: '', zoom: null })
    expect(parseLocalMediaHtml(videoOpening)).toEqual({ kind: 'video', source: videoSource, alt: '', zoom: null })
    expect(isLocalMediaClosingHtml('</audio>')).toBe(true)
    expect(isLocalMediaClosingHtml('</video>')).toBe(true)
    expect(isLocalMediaClosingHtml('</script>')).toBe(false)
  })

  it('recognizes only local Markdown image attributes', () => {
    expect(parseLocalMarkdownImage({
      src: 'C:\\Workspace\\assets\\photo.png',
      alt: '照片',
    })).toEqual({
      kind: 'image',
      source: 'C:\\Workspace\\assets\\photo.png',
      alt: '照片',
      zoom: null,
      alignment: 'center',
    })
    expect(parseLocalMarkdownImage({ src: 'https://example.com/photo.png' })).toBeNull()
    expect(parseLocalMarkdownImage({ src: 'C:\\Workspace\\note.txt' })).toBeNull()
  })

  it('resolves a relative Markdown image from the current document without rewriting its source', () => {
    expect(parseLocalMarkdownImage({
      src: './audit-assets/02-arknote-settings.png',
      alt: 'Arknote settings',
    }, 'C:\\Workspace\\docs\\ui\\ui-spec.md')).toEqual({
      kind: 'image',
      source: './audit-assets/02-arknote-settings.png',
      previewSource: 'C:\\Workspace\\docs\\ui\\audit-assets\\02-arknote-settings.png',
      alt: 'Arknote settings',
      zoom: null,
      alignment: 'center',
    })

    expect(parseLocalMarkdownImage(
      { src: './audit-assets/02-arknote-settings.png' },
      null,
    )).toBeNull()
  })

  it('keeps the relative source when image presentation changes', () => {
    const parsed = parseLocalMarkdownImage(
      { src: '../images/photo.png', alt: 'Photo' },
      'C:\\Workspace\\docs\\ui-spec.md',
    )
    const updated = updateLocalImageDescriptor(parsed!, { alignment: 'left' })

    expect(updated).toMatchObject({
      source: '../images/photo.png',
      previewSource: 'C:\\Workspace\\images\\photo.png',
      alignment: 'left',
    })
    expect(serializeLocalImage(updated!)).toContain('src="../images/photo.png"')
  })
  it('hides only a matching canonical companion closing atom', () => {
    expect(localMediaClosingMatchesOpening('</audio>', audioOpening)).toBe(true)
    expect(localMediaClosingMatchesOpening('</video>', videoOpening)).toBe(true)
    expect(localMediaClosingMatchesOpening('</audio>', videoOpening)).toBe(false)
    expect(localMediaClosingMatchesOpening('</audio>', '<audio src="./clip.mp3">')).toBe(false)
    expect(localMediaClosingMatchesOpening('</audio>', null)).toBe(false)
  })

  it.each([
    '<audio controls src="https://example.com/a.mp3"></audio>',
    `<audio autoplay controls preload="metadata" src="${audioSource}"></audio>`,
    `<video controls preload="metadata" src="${videoSource}?query=1"></video>`,
    '<script>alert(1)</script>',
    'ordinary HTML',
  ])('rejects unsafe or noncanonical HTML: %s', (value) => {
    expect(parseLocalMediaHtml(value)).toBeNull()
  })
})

describe('local media element', () => {
  it('creates an audio element with native controls', () => {
    const created = createLocalMediaElement(audioHtml, document)
    expect(created).not.toBeNull()
    expect(created!.element).toBeInstanceOf(HTMLAudioElement)
    expect(created!.element.controls).toBe(true)
    expect(created!.element.preload).toBe('metadata')
    expect(created!.element.getAttribute('src')).toBe(externalAssetUrl(audioSource))
    created!.destroy()
  })

  it('shows video controls on hover, focus, or playback and hides them when idle', () => {
    const created = createLocalMediaElement(videoHtml, document)
    expect(created).not.toBeNull()
    const video = created!.element as HTMLVideoElement
    document.body.append(video)

    expect(video.controls).toBe(false)
    fireEvent.mouseEnter(video)
    expect(video.controls).toBe(true)
    fireEvent.mouseLeave(video)
    expect(video.controls).toBe(false)

    video.focus()
    expect(video.controls).toBe(true)
    video.blur()
    expect(video.controls).toBe(false)

    fireEvent.play(video)
    fireEvent.mouseLeave(video)
    expect(video.controls).toBe(true)
    fireEvent.pause(video)
    expect(video.controls).toBe(false)

    created!.destroy()
    video.remove()
  })

})
describe('local image context updates', () => {
  const image = {
    kind: 'image' as const,
    source: 'C:\\Workspace\\assets\\photo.png',
    alt: '旧文字',
    zoom: 100,
    alignment: 'center' as const,
  }

  it('keeps alignment icons at 22 visible pixels across display scaling', () => {
    expect(imageAlignmentIconCssSize(1)).toBe(22)
    expect(imageAlignmentIconCssSize(1.5)).toBeCloseTo(14.667, 3)
    expect(imageAlignmentIconCssSize(0)).toBe(22)
  })

  it('updates only the document descriptor and clamps zoom safely', () => {
    const updated = updateLocalImageDescriptor(image, {
      source: 'C:\\Workspace\\copies\\photo.png',
      alt: '新文字',
      zoom: 800,
    })
    expect(updated).toEqual({
      kind: 'image',
      source: 'C:\\Workspace\\copies\\photo.png',
      alt: '新文字',
      zoom: 400,
      alignment: 'center',
    })
    expect(serializeLocalImage(updated!)).toContain('zoom:400%')
  })

  it('parses, updates, and serializes persistent image alignment', () => {
    const left = updateLocalImageDescriptor(image, { alignment: 'left' })
    expect(left?.alignment).toBe('left')
    expect(serializeLocalImage(left!)).toContain(
      'display:block;margin-left:0;margin-right:auto;',
    )

    const parsed = parseLocalMediaHtml(
      '<img src="C:\\Workspace\\assets\\photo.png" alt="照片" '
      + 'style="display:block;margin-left:auto;margin-right:0;" />',
    )
    expect(parsed).toMatchObject({ kind: 'image', alignment: 'right' })
  })

  it('rejects non-image or relative replacement references', () => {
    expect(updateLocalImageDescriptor(image, { source: '..\\photo.png' })).toBeNull()
    expect(updateLocalImageDescriptor(image, { source: 'C:\\Workspace\\note.txt' })).toBeNull()
  })
})
